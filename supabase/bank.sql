-- Aereon Dashboard — Cash flow: the company bank account, line by line, from the statements the accountant keeps.
-- Additive: two new tables, nothing existing touched. Safe to run twice. No data here: the repo is public, so the
-- lines are loaded by `npm run bank:parse -- --upload` (scripts/bank-statements.mjs) from the git-ignored .bank-data/.

-- One row per monthly statement: which days it covers and how it opens and closes. A month the statements don't
-- cover shows as "no statement" on the page, never as zero.
create table if not exists bank_statement (
  account      text    not null,            -- last 4 digits of the account number
  period_from  date    not null,
  period_to    date    not null,
  opening      numeric(14,2),
  closing      numeric(14,2),
  source_file  text,                        -- the PDF's name in the accountant's Drive folder
  created_at   timestamptz not null default now(),
  primary key (account, period_to)
);

-- One row per statement line. + amount = money in, − = money out.
create table if not exists bank_txn (
  id           bigint generated by default as identity primary key,
  account      text    not null,
  statement    date    not null,            -- the statement's last day (bank_statement.period_to)
  seq          int     not null,            -- line number on that statement
  txn_date     date    not null,
  amount       numeric(14,2) not null,
  balance      numeric(14,2),               -- printed only on the last line of a day
  type         text    not null,            -- the bank's wording, e.g. "Cr Adv-Interbank GIRO at KLM"
  party        text,                        -- payer / payee as printed
  note         text,                        -- the payer's own reference
  bank_ref     text,
  description  text    not null,            -- every description line, joined with " | "
  source_file  text,
  -- Set by the owner on the Cash flow page; null = let the app decide (lib/bank-math.ts).
  kind         text,                        -- override of flowKind: client, owner, salary, supplier, …
  invoice_ids  bigint[],                    -- override of the match: these invoices, or {} for "not an invoice"
  created_at   timestamptz not null default now(),
  unique (account, statement, seq)
);
create index if not exists bank_txn_date_idx on bank_txn (txn_date desc);

-- Server-side only, like every other table here: RLS on, no policies.
alter table bank_statement enable row level security;
alter table bank_txn enable row level security;
